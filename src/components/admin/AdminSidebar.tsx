export default function AdminSidebar() {
  const location = useLocation();
  const navigate = useNavigate();
  const { user } = useAuth();
  const [logoUrl, setLogoUrl] = useState<string | null>(null);

  useEffect(() => {
    configurationService.getAll()
      .then((config) => {
        if (config.logo) {
          setLogoUrl(storageUrl(config.logo));
        }
      })
      .catch(() => {});
  }, []);

  const filteredMenu = menuItems.filter((item) =>
    item.roles.includes(user?.role || '')
  );

  return (
    <aside className="fixed left-0 top-0 h-screen w-64 bg-primary flex flex-col z-40">
      {/* Logo + Brand */}
      <div className="p-6 border-b border-white/10">
        <Link to="/" className="flex items-center gap-3">
          {logoUrl ? (
            <img
              src={logoUrl}
              alt="Logo"
              className="h-8 w-auto object-contain"
            />
          ) : (
            <div className="w-8 h-8 bg-white/10 rounded-lg flex items-center justify-center">
              <span className="text-white font-display text-sm">J</span>
            </div>
          )}
          <span className="font-display text-lg text-white">Jurnalistik</span>
        </Link>
      </div>

      {/* Menu */}
      <nav className="flex-1 px-3 py-4 space-y-0.5 overflow-y-auto">
        {filteredMenu.map((item) => {
          const currentPath = location.pathname.replace(/\/+$/, '') || '/';
          const isActive = currentPath === item.to || 
            (currentPath.startsWith(item.to + '/') && 
             item.to !== '/dashboard/admin' && 
             item.to !== '/dashboard/kontributor');
          return (
            <Link
              key={item.to}
              to={item.to}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all duration-200 ${
                isActive
                  ? 'bg-white/15 text-white'
                  : 'text-white/60 hover:bg-white/5 hover:text-white/90'
              }`}
            >
              {item.icon}
              <span>{item.label}</span>
            </Link>
          );
        })}
      </nav>

      {/* Footer */}
      <div className="p-3 border-t border-white/10">
        <button
          onClick={() => navigate('/')}
          className="flex items-center gap-2 w-full px-3 py-2.5 rounded-lg text-white/50 hover:bg-white/5 hover:text-white/80 transition-all duration-200 text-sm"
        >
          <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M10 19l-7-7m0 0l7-7m-7 7h18" />
          </svg>
          <span>Kembali ke Website</span>
        </button>
      </div>
    </aside>
  );
}